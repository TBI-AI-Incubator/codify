def _split_params(inner: str) -> list[str]:
    """Split a rendered parameter list on its top-level commas, outside quoted defaults."""
    parts, depth, start, quote, escaped = [], 0, 0, "", False
    for i, ch in enumerate(inner):
        if quote:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == quote:
                quote = ""
            continue
        if ch in "'\"":
            quote = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append(inner[start:i].strip())
            start = i + 1
    parts.append(inner[start:].strip())
    return parts


def signature(name: str, obj: object) -> str:
    try:
        sig = inspect.signature(obj)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return name

    class Raw(str):
        """An annotation kept as source text, shown without quotes."""

        def __repr__(self) -> str:
            return str(self)

    def bare(ann: object) -> object:
        return Raw(ann) if isinstance(ann, str) else ann

    def shown(value: object) -> object:
        # A function default prints its memory address; name it instead.
        return Raw(value.__name__) if inspect.isfunction(value) else value

    # Re-rendered whole, so the `/` and `*` markers survive as the code states them.
    plain = sig.replace(
        parameters=[
            p.replace(annotation=bare(p.annotation), default=shown(p.default))
            for p in sig.parameters.values()
        ],
        return_annotation=inspect.Signature.empty,
    )
    inner = str(plain)[1:-1]
    params = _split_params(inner) if inner else []
    ret = sig.return_annotation
    ret = (
        ""
        if ret is inspect.Signature.empty or inspect.isclass(obj)
        else f" -> {inspect.formatannotation(bare(ret))}"
    )
    prefix = (
        "class "
        if inspect.isclass(obj)
        else ("async def " if inspect.iscoroutinefunction(obj) else "def ")
    )
    one = f"{prefix}{name}({', '.join(params)}){ret}"
    if len(one) <= 88:
        return one
    return f"{prefix}{name}(\n" + "".join(f"    {p},\n" for p in params) + f"){ret}"


