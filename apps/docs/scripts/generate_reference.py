def cli_page() -> tuple[str, str]:
    from codify.cli import build_parser

    parser = build_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {a.dest: a.help for a in sub._choices_actions}
    grouped = [name for _, _, names in CLI_GROUPS for name in names]
    missing = sorted(set(sub.choices) - set(grouped))
    stale = sorted(set(grouped) - set(sub.choices))
    if missing or stale:
        sys.exit(f"cli: add {missing} to CLI_GROUPS, remove {stale}")

    out = [
        "Every `codify` command, read from the parser the command line builds. "
        "Commands are grouped in the order the guide uses them. Flag defaults that come "
        "from the environment are shown as the code's own fallback; see "
        "[Environment variables](environment.md).",
    ]
    for title, guide, names in CLI_GROUPS:
        out.append(f"## {title}")
        if guide:
            out.append(f"Guide: [{title}]({guide}).")
        for name in names:
            cmd = sub.choices[name]
            usage = re.sub(r"\s+", " ", cmd.format_usage().removeprefix("usage: ")).strip()
            out += [f"### `{name}`", text(helps[name]) + ".", f"```bash\n{usage}\n```"]
            rows = []
            for a in cmd._actions:
                if isinstance(a, argparse._HelpAction):
                    continue
                flag = ", ".join(a.option_strings) or a.dest
                if a.option_strings and a.nargs != 0:
                    flag += f" {a.metavar or a.dest.upper()}"
                if a.nargs == 0:
                    kind = "flag"
                elif a.type is None:
                    kind = "string"
                else:
                    kind = {"int": "integer", "_positive": "positive integer"}.get(
                        a.type.__name__, a.type.__name__
                    )
                default = (
                    "" if a.default in (None, False, "") or a.required else default_text(a.default)
                )
                hint = (a.help or "") % {**vars(a), "prog": cmd.prog} if a.help else ""
                rows.append(
                    [
                        code(flag),
                        kind,
                        "required" if a.required or not a.option_strings else default,
                        ", ".join(code(c) for c in a.choices) if a.choices else "",
                        cell(hint),
                    ]
                )
            header = ["Argument", "Type", "Default", "Choices", "Description"]
            if not any(r[3] for r in rows):
                header.pop(3)
                rows = [r[:3] + r[4:] for r in rows]
            if rows:
                out.append(table(header, rows))
            else:
                out.append("No arguments.")
    return page(
        "cli",
        "Command line",
        "Every codify command and subcommand with its arguments, types, defaults and help, generated from the parser.",
        1,
        "\n\n".join(out),
    )


