def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--core", type=Path, default=REPO, help="core checkout to read (default: this repository)"
    )
    core = ap.parse_args().core.resolve()
    sys.path.insert(0, str(core))
    # Flag defaults read the environment; clear it so the pages do not depend on the shell.
    for name in yaml.safe_load((HERE / "environment.yml").read_text(encoding="utf-8")):
        os.environ.pop(name, None)
    import codify

    if not Path(codify.__file__).resolve().is_relative_to(core):
        sys.exit(
            f"codify imports from {codify.__file__}, not {core}; run with that checkout's environment"
        )
    pages = [
        cli_page(),
        http_page(core),
        mcp_page(),
        python_page(),
        config_page(core),
        environment_page(core),
    ]
    for name, content in pages:
        (OUT / name).write_text(content, encoding="utf-8")
        print(f"wrote docs/reference/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
