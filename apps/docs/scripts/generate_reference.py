# Environment

SECRET = re.compile(r"KEY|AUTH|TOKEN|SECRET|PASSWORD")
TEST_MODULES = ("codify.testing", "codify.eval.")


def env_reads(core: Path) -> tuple[dict[str, dict[str, set[str]]], list[str]]:
    """Variable name to module to defaults, from every literal read; and modules with computed names."""
    found: dict[str, dict[str, set[str]]] = {}
    computed: list[str] = []
    for path in sorted((core / "codify").rglob("*.py")):
        module = ".".join(path.relative_to(core).with_suffix("").parts).removesuffix(".__init__")
        tree = ast.parse(path.read_text(encoding="utf-8"))
        consts = {
            t.id: n.value.value
            for n in tree.body
            if isinstance(n, ast.Assign) and isinstance(n.value, ast.Constant)
            for t in n.targets
            if isinstance(t, ast.Name)
        }
        parents = {c: p for p in ast.walk(tree) for c in ast.iter_child_nodes(p)}
        helper = {
            id(n)
            for f in ast.walk(tree)
            if isinstance(f, ast.FunctionDef) and f.name == "_env"
            for n in ast.walk(f)
        }

        def literal(node: ast.AST) -> str | None:
            if isinstance(node, ast.Constant) and isinstance(node.value, (str, int)):
                return str(node.value)
            if isinstance(node, ast.Name) and isinstance(consts.get(node.id), (str, int)):
                return str(consts[node.id])
            return None

        for node in ast.walk(tree):
            names: list[ast.AST] = []
            default = None
            if isinstance(node, ast.Call):
                fn = ast.unparse(node.func)
                if fn in ("os.environ.get", "os.getenv", "environ.get", "getenv") and node.args:
                    names = [node.args[0]]
                    if len(node.args) > 1:
                        default = literal(node.args[1])
                elif fn == "_env":
                    names = list(node.args)
            elif isinstance(node, ast.Subscript) and ast.unparse(node.value) in (
                "os.environ",
                "environ",
            ):
                if isinstance(node.ctx, ast.Load):
                    names = [node.slice]
            if not names or id(node) in helper:
                continue
            parent = parents.get(node)
            if isinstance(parent, ast.BoolOp) and isinstance(parent.op, ast.Or) and default is None:
                default = literal(parent.values[-1])
            for n in names:
                if name := literal(n):
                    defaults = found.setdefault(name, {}).setdefault(module, set())
                    if default is not None:
                        defaults.add(default)
                elif module not in computed:
                    computed.append(module)
    return found, computed


def environment_page(core: Path) -> tuple[str, str]:
    described = yaml.safe_load((HERE / "environment.yml").read_text(encoding="utf-8"))
    found, computed = env_reads(core)
    undescribed = sorted(set(found) - set(described))
    stale = sorted(set(described) - set(found))
    if undescribed or stale:
        sys.exit(f"environment.yml: describe {undescribed}; remove {stale}")

    def row(name: str) -> list[str]:
        modules = found[name]
        defaults = sorted(set().union(*modules.values()))
        if defaults and SECRET.search(name):
            shown = "built-in value"
        else:
            shown = ", ".join(code(d) if d else "empty string" for d in defaults)
        return [
            code(name),
            shown,
            ", ".join(code(m) for m in sorted(modules)),
            cell(described[name]),
        ]

    header = ["Variable", "Default in code", "Read in", "Description"]
    test = [n for n in sorted(found) if all(m.startswith(TEST_MODULES) for m in found[n])]
    runtime = [n for n in sorted(found) if n not in test]
