def ann_type(ann: typing.Any, queue: list[type]) -> str:
    from pydantic import BaseModel

    origin = typing.get_origin(ann)
    args = typing.get_args(ann)
    if isinstance(ann, typing.TypeAliasType):
        return ann_type(ann.__value__, queue)
    if origin is typing.Annotated:
        return ann_type(args[0], queue)
    if origin in (typing.Union, types.UnionType):
        return " or ".join(ann_type(a, queue) for a in args)
    if origin is typing.Literal:
        return " or ".join(code(json.dumps(a)) for a in args)
    if origin in (list, set, frozenset, tuple):
        return "list of " + " or ".join(ann_type(a, queue) for a in args if a is not Ellipsis)
    if origin is dict:
        return f"map of {ann_type(args[0], queue)} to {ann_type(args[1], queue)}"
    if ann is type(None):
        return "null"
    if inspect.isclass(ann) and issubclass(ann, BaseModel):
        queue.append(ann)
        return f"[{ann.__name__}](#{slug(ann.__name__)})"
    if inspect.isclass(ann) and issubclass(ann, enum.Enum):
        return " or ".join(code(json.dumps(m.value)) for m in ann)
    names = {str: "string", int: "integer", float: "number", bool: "boolean", typing.Any: "any"}
    return names.get(ann, getattr(ann, "__name__", str(ann)))


