def schema_type(s: dict[str, typing.Any], refs: set[str]) -> str:
    if "$ref" in s:
        name = s["$ref"].rsplit("/", 1)[1]
        refs.add(name)
        if name == "JurisdictionConfig":
            return "[JurisdictionConfig](jurisdiction-config.md)"
        return f"[{name}](#{slug(name)})"
    if "anyOf" in s or "oneOf" in s:
        return " or ".join(schema_type(x, refs) for x in s.get("anyOf", s.get("oneOf")))
    if "const" in s:
        return code(json.dumps(s["const"]))
    if "enum" in s:
        return " or ".join(code(json.dumps(v)) for v in s["enum"])
    kind = s.get("type")
    if kind == "array":
        return "array of " + schema_type(s.get("items", {}), refs)
    if kind == "object" and isinstance(s.get("additionalProperties"), dict):
        return "object of " + schema_type(s["additionalProperties"], refs)
    if kind == "string" and s.get("format"):
        return f"string ({s['format']})"
    if kind == "string" and s.get("contentMediaType"):
        return "file"
    return kind or "any"


def constraints(s: dict[str, typing.Any]) -> str:
    names = {
        "minimum": "min",
        "maximum": "max",
        "minLength": "min length",
        "maxLength": "max length",
        "pattern": "pattern",
    }
    return ", ".join(f"{label} {code(s[k])}" for k, label in names.items() if k in s)


def schema_rows(s: dict[str, typing.Any], refs: set[str]) -> list[list[str]]:
    required = set(s.get("required", []))
    rows = []
    for name, prop in s.get("properties", {}).items():
        rows.append(
            [
                code(name),
                schema_type(prop, refs),
                "required"
                if name in required
                else (default_text(prop["default"]) if "default" in prop else ""),
                cell(" ".join(filter(None, [prop.get("description", ""), constraints(prop)]))),
            ]
        )
    return rows


def http_page(core: Path) -> tuple[str, str]:
    contract = json.loads((core / "contract" / "openapi.json").read_text(encoding="utf-8"))
    schemas = contract["components"]["schemas"]
    refs: set[str] = set()
    sections: dict[str, list[str]] = {title: [] for title, _, _ in HTTP_GROUPS}
    for path, ops in contract["paths"].items():
        group = next((g for g in HTTP_GROUPS if path == g[1] or path.startswith(g[1] + "/")), None)
        if group is None:
            sys.exit(f"http: add a group for {path} to HTTP_GROUPS")
        for method, op in ops.items():
            part = [f"### `{method.upper()} {path}`"]
            if op.get("description"):
                part.append(text(op["description"]))
            params = op.get("parameters", [])
            if params:
                part.append(
                    table(
                        ["Parameter", "In", "Type", "Default", "Description"],
                        [
                            [
                                code(p["name"]),
                                p["in"],
                                schema_type(p["schema"], refs),
                                "required"
                                if p.get("required")
                                else (
                                    default_text(p["schema"]["default"])
                                    if "default" in p["schema"]
                                    else ""
                                ),
                                cell(
                                    " ".join(
                                        filter(
                                            None,
                                            [p.get("description", ""), constraints(p["schema"])],
                                        )
                                    )
                                ),
                            ]
                            for p in params
                        ],
                    )
                )
            for media, body in op.get("requestBody", {}).get("content", {}).items():
                part.append(f"Request body (`{media}`): {schema_type(body['schema'], refs)}.")
            rows = []
            for status, resp in op["responses"].items():
                content = resp.get("content", {})
                kinds = "; ".join(
                    f"`{m}` {schema_type(c.get('schema', {}), refs)}" for m, c in content.items()
                )
                rows.append([code(status), cell(resp.get("description", "")), kinds])
            part.append(table(["Status", "Meaning", "Body"], rows))
            sections[group[0]].append("\n\n".join(part))

    # Schemas reached from an operation, followed through their own fields.
    seen: list[str] = []
    queue = sorted(refs)
    while queue:
        name = queue.pop(0)
        if name in seen or name == "JurisdictionConfig":
            continue
        seen.append(name)
        nested: set[str] = set()
        schema_rows(schemas[name], nested)
        queue += sorted(nested - set(seen))

    version = contract["info"]["version"]
    out = [
        f"The routes `codify serve` answers, read from the checked-in contract "
        f"[`contract/openapi.json`](../../contract/openapi.json) (version {code(version)}). "
        "`codify serve --openapi` prints the same schema. Each group links to the guide page that uses it.",
    ]
    for title, prefix, guide in HTTP_GROUPS:
        out += [
            f"## {title}",
            f"Guide: [{guide.rsplit('/', 1)[1].removesuffix('.md').replace('-', ' ').capitalize()}]({guide}).",
        ]
        out += sections[title]
    out.append("## Schemas")
    out.append(
        "Every schema a route takes or returns. [JurisdictionConfig](jurisdiction-config.md) has its own page."
    )
    for name in sorted(seen):
        s = schemas[name]
        part = [f"### {name}"]
        if s.get("description"):
            part.append(text(s["description"]))
        if s.get("properties"):
            part.append(table(["Field", "Type", "Default", "Description"], schema_rows(s, set())))
        elif "enum" in s:
            part.append("One of " + ", ".join(code(json.dumps(v)) for v in s["enum"]) + ".")
        else:
            part.append(f"Type: {schema_type(s, set())}.")
        out.append("\n\n".join(part))
    return page(
        "http-api",
        "HTTP API",
        "Every route of the codify serve HTTP server with its parameters, request body and response schemas, generated from the OpenAPI contract.",
        2,
        "\n\n".join(out),
    )


