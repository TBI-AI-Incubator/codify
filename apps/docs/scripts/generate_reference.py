# Markdown helpers


def slug(heading: str) -> str:
    """The anchor Starlight gives a heading (github-slugger rules)."""
    text = heading.lower().replace("`", "")
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def text(value: object) -> str:
    """Prose for Markdown: `<` and `>` escaped outside code spans so they are not read as HTML."""
    parts = str(value).split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("<", "&lt;").replace(">", "&gt;")
    return "`".join(parts)


def cell(value: object) -> str:
    return text(re.sub(r"\s+", " ", str(value)).strip()).replace("|", "\\|")


def code(value: object) -> str:
    raw = str(value).replace("|", "\\|")
    return f"`` {raw} ``" if "`" in raw else f"`{raw}`"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def page(slug_: str, title: str, description: str, order: int, body: str) -> tuple[str, str]:
    front = (
        f"---\ntitle: {title}\ndescription: {description}\nsidebar:\n  order: {order}\n---\n"
        f"<!-- Generated by apps/docs/scripts/generate_reference.py; do not edit. "
        f"Regenerate from the repository root: {REGEN} -->\n\n"
    )
    return f"{slug_}.md", front + body.strip() + "\n"


def default_text(value: object) -> str:
    try:
        return code(json.dumps(value, ensure_ascii=False))
    except TypeError:
        return code(repr(value))


